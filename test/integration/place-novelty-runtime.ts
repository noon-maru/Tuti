import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { Pool } from "pg";
import { PrismaPg } from "@prisma/adapter-pg";
import { PrismaClient } from "../../src/generated/prisma/client";

const socket = process.argv[2];
assert.ok(socket.includes("tuti-legal-postgres-") && socket.endsWith("/socket"));
const schema = "tuti_novelty_fixture";
const connection = { host: socket, port: 15479, user: "tuti_legal_test", database: "postgres", ssl: false as const, options: `-c search_path=${schema},public` };
const pool = new Pool(connection);
const client = new PrismaClient({ adapter: new PrismaPg({ ...connection, max: 3 }, { schema }) });
process.env.DATABASE_URL = "postgresql://unused:unused@127.0.0.1:1/unused";
(globalThis as { prisma?: unknown }).prisma = client;
try {
  await pool.query(`CREATE SCHEMA ${schema}; SET search_path=${schema},public;
    CREATE TYPE "PlaceReviewStatus" AS ENUM ('pending','approved','rejected');
    CREATE TYPE "PlaceCandidateOverride" AS ENUM ('auto','include','exclude');
    CREATE TYPE "PlaceCandidateStatus" AS ENUM ('selected','enrich','pending','low_burden_mismatch','invalid');
    CREATE TABLE users(id text PRIMARY KEY);
    CREATE TABLE places(id text PRIMARY KEY,source text,is_active boolean,review_status "PlaceReviewStatus",candidate_override "PlaceCandidateOverride",candidate_status "PlaceCandidateStatus");
    CREATE TABLE recommendation_actions(journey_id text,user_id text,place_id text,action text,created_at timestamp);
    CREATE TABLE journal_entries(owner_id text,place_id text,sensitive_withdrawn_at timestamp,created_at timestamp);
    INSERT INTO users VALUES('a'),('b');
    INSERT INTO places SELECT id,'tourapi',true,'approved','auto','selected' FROM unnest(ARRAY['p1','p2','p3','p4']) AS id;
    INSERT INTO recommendation_actions VALUES('same-run','a','p1','place_selected','2026-11-12'),('same-run','a','p1','place_selected','2026-11-12'),('other-run','b','p2','place_selected','2026-11-12');
    INSERT INTO journal_entries VALUES('a','p3',NULL,'2026-11-12'),('b','p2',NULL,'2026-11-12');`);
  await pool.query(readFileSync("prisma/migrations/20261113010000_place_familiarity/migration.sql", "utf8"));
  const { loadPlaceNoveltySignals, rankWithNovelty } = await import("../../src/server/recommendations/novelty");
  const { readPlaceFamiliarity, setPlaceFamiliarity, mergePlaceFamiliarities } = await import("../../src/server/recommendations/familiarity");
  const now = new Date("2026-11-13T00:00:00Z");
  await setPlaceFamiliarity("a", "p4", true, now, client);
  await setPlaceFamiliarity("a", "p4", true, now, client);
  await setPlaceFamiliarity("b", "p4", true, now, client);
  assert.equal((await pool.query("SELECT count(*)::int AS n FROM place_familiarities")).rows[0].n, 2);
  const signals = await loadPlaceNoveltySignals("a", ["p1", "p2", "p3", "p4"], now, client);
  assert.ok(signals, "정상 조회가 fail-open으로 숨겨지면 안 된다.");
  assert.equal(signals.find(row => row.placeId === "p1")?.exposures, 1);
  assert.equal(signals.find(row => row.placeId === "p2"), undefined, "다른 사용자의 노출·기록은 섞이지 않는다.");
  assert.equal(signals.find(row => row.placeId === "p3")?.recorded, true);
  assert.equal(signals.find(row => row.placeId === "p4")?.familiar, true);
  const places = ["p1", "p2", "p3", "p4"].map(id => ({ id, name: id, phrase: "", note: "", image: "", travelTime: "", crowd: "", today: "", fatigue: 30, movementLevel: "near" as const, moodTags: [] }));
  assert.deepEqual(rankWithNovelty(places, signals).map(row => row.id), ["p2", "p1", "p3", "p4"]);
  await setPlaceFamiliarity("a", "p4", false, now, client);
  assert.equal((await readPlaceFamiliarity("a", "p4", now, client)).familiar, false);
  assert.equal((await readPlaceFamiliarity("b", "p4", now, client)).familiar, true);
  await pool.query("UPDATE place_familiarities SET marked_at='2026-01-01',expires_at='2026-06-30' WHERE user_id='b'");
  assert.equal((await readPlaceFamiliarity("b", "p4", now, client)).familiar, false);
  assert.equal((await client.placeFamiliarity.deleteMany({ where: { expiresAt: { lte: now } } })).count, 1);
  await setPlaceFamiliarity("a", "p4", true, now, client);
  await client.$transaction(tx => mergePlaceFamiliarities(tx, "a", "b", now));
  await pool.query("DELETE FROM users WHERE id='a'");
  assert.equal((await pool.query("SELECT count(*)::int AS n FROM place_familiarities WHERE user_id='a'")).rows[0].n, 0);
  assert.equal((await readPlaceFamiliarity("b", "p4", now, client)).familiar, true, "명시적으로 병합한 계정의 표시를 보존한다.");
  await setPlaceFamiliarity("b", "p4", true, now, client);
  await pool.query("DELETE FROM places WHERE id='p4'");
  assert.equal((await pool.query("SELECT count(*)::int AS n FROM place_familiarities")).rows[0].n, 0);
  await assert.rejects(pool.query("INSERT INTO place_familiarities VALUES('missing','p1',now(),now()+interval '1 day')"));
  await assert.rejects(pool.query("INSERT INTO place_familiarities VALUES('b','p1',now(),now())"));
  await pool.query("DROP TABLE place_familiarities");
  assert.equal(await loadPlaceNoveltySignals("b", ["p1"], now, client), null, "표시 저장소가 없으면 일반 추천 순위로 복귀한다.");
  console.log("격리 DB: 가점·계정 격리·재전송·취소·만료·연쇄 파기 검증 완료");
} finally {
  await client.$disconnect();
  await pool.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
  await pool.end();
  delete (globalThis as { prisma?: unknown }).prisma;
}
