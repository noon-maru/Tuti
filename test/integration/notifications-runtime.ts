import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { Pool } from "pg";
import { PrismaClient } from "../../src/generated/prisma/client";
import { PrismaPg } from "@prisma/adapter-pg";
const socket = process.argv[2];
assert.ok(socket.includes("tuti-legal-postgres-") && socket.endsWith("/socket"));
const schema = "tuti_notifications_fixture";
const connection = { host: socket, port: 15479, user: "tuti_legal_test", database: "postgres", ssl: false as const, options: `-c search_path=${schema},public -c timezone=UTC` };
const pool = new Pool(connection);
const client = new PrismaClient({ adapter: new PrismaPg({ ...connection, max: 4 }, { schema }) });
process.env.DATABASE_URL = "postgresql://unused:unused@127.0.0.1:1/unused";
process.env.HARUMADI_TOGETHER_ENABLED = "true";
(globalThis as { prisma?: unknown }).prisma = client;
try {
  await pool.query(`CREATE SCHEMA ${schema};
    CREATE TABLE users(id text PRIMARY KEY);
    CREATE TABLE harumadis(id text PRIMARY KEY,owner_id text REFERENCES users(id) ON DELETE CASCADE,title text NOT NULL DEFAULT 'synthetic',revision int DEFAULT 1,access_revision int DEFAULT 0,collaboration_started_at timestamp);
    CREATE TABLE harumadi_members(id text,harumadi_id text,user_id text,joined_at timestamp DEFAULT now(),ended_at timestamp);
    CREATE TABLE journal_entries(id text PRIMARY KEY,owner_id text,created_at timestamp DEFAULT now(),sensitive_content boolean DEFAULT false);
    CREATE TABLE harumadi_entry_links(id text,harumadi_id text,entry_id text);
    CREATE TABLE harumadi_comments(id text,harumadi_id text,author_id text,parent_id text,deleted_at timestamp);
    CREATE TABLE journal_author_blocks(blocker_user_id text,blocked_user_id text);
    CREATE TABLE push_devices(user_id text,enabled boolean,invalidated_at timestamp);
    INSERT INTO users VALUES('owner'),('member'),('third'),('outsider');
    INSERT INTO harumadis(id,owner_id,revision,access_revision,collaboration_started_at) VALUES('book','owner',1,0,now());
    INSERT INTO harumadi_members(id,harumadi_id,user_id) VALUES('m1','book','member'),('m2','book','third');
    INSERT INTO journal_entries(id,owner_id) VALUES('entry','member');
    INSERT INTO harumadi_entry_links VALUES('link','book','entry');
    INSERT INTO push_devices VALUES('owner',true,null);`);
  await pool.query(readFileSync("prisma/migrations/20261103020000_lifelog_notifications/migration.sql", "utf8"));
  await pool.query(readFileSync("prisma/migrations/20261106130000_inquiry_notification_outbox/migration.sql", "utf8"));
  await pool.query("CREATE TABLE customer_inquiries(id text PRIMARY KEY,requester_user_id text,admin_response text,updated_at timestamp(3))");
  const { readNotificationSettings, saveNotificationSettings, bookNotificationSettings } = await import("../../src/server/notifications/settings");
  const { enqueueTogetherNotification } = await import("../../src/server/notifications/outbox");
  const { dispatchNotifications } = await import("../../src/server/notifications/dispatch");
  const settings = { newsEnabled: true, reminderEnabled: false, reminderTime: "19:00", timeZone: "Asia/Seoul" };
  assert.equal((await readNotificationSettings("owner")).reminderTime, "19:00");
  for (const user of ["owner","member","third"]) await saveNotificationSettings(user, settings);
  await assert.rejects(bookNotificationSettings("outsider", "book", true), { status: 404 });
  await bookNotificationSettings("third", "book", true);
  const queue = () => client.$transaction(tx => enqueueTogetherNotification(tx, "member", "book", "shared-madi", "link"));
  await queue(); await queue();
  assert.equal((await pool.query("SELECT count(1)::int AS n FROM notification_jobs")).rows[0].n, 2, "자기 행동·음소거한 사람은 제외");
  await pool.query("UPDATE notification_jobs SET due_at=now()-interval '1 second'");
  const sent: { user: string; type: string }[] = [];
  const send = async (user: string, message: { type: string }) => { sent.push({ user, type: message.type }); return { attempted: 1, sent: 1, failed: 0, invalidated: 0 }; };
  await dispatchNotifications(true, new Date(), send);
  assert.equal(sent.length, 1, "동일 책의 추가는 한 번으로 묶음");
  await dispatchNotifications(true, new Date(), send); assert.equal(sent.length, 1);
  await queue(); await pool.query("UPDATE notification_jobs SET due_at=now()-interval '1 second'; UPDATE harumadi_members SET ended_at=now() WHERE user_id='member'");
  await dispatchNotifications(true, new Date(), send); assert.equal(sent.length, 1, "나간 작성자의 대기 알림 억제");
  await pool.query("UPDATE harumadi_members SET ended_at=null WHERE user_id='member'; INSERT INTO journal_author_blocks VALUES('owner','member')");
  await queue(); await pool.query("UPDATE notification_jobs SET due_at=now()-interval '1 second'");
  await dispatchNotifications(true, new Date(), send); assert.equal(sent.length, 1, "차단 이후 발송 억제");
  await pool.query("DELETE FROM journal_author_blocks");
  await queue(); await saveNotificationSettings("owner", { ...settings, newsEnabled: false });
  await pool.query("UPDATE notification_jobs SET due_at=now()-interval '1 second'");
  await dispatchNotifications(true, new Date(), send); assert.equal(sent.length, 1, "설정 끄기 이후 대기 알림 폐기");
  const now = new Date(); const { notificationLocalClock } = await import("../../src/shared/notifications/preferences");
  const clock = notificationLocalClock(now, "Asia/Seoul");
  await saveNotificationSettings("owner", { ...settings, newsEnabled: false, reminderEnabled: true, reminderTime: clock.time });
  await dispatchNotifications(true, now, send); assert.equal(sent.length, 2, "오늘 미작성자는 기록 알림 발송");
  await dispatchNotifications(true, now, send); assert.equal(sent.length, 2, "같은 날 재실행해도 두 번 발송하지 않음");
  await pool.query("DELETE FROM notification_jobs WHERE kind='madi-reminder'; INSERT INTO journal_entries(id,owner_id) VALUES('written-today','owner')");
  await dispatchNotifications(true, now, send); assert.equal(sent.length, 2, "방문일 아닌 실제 생성일 기준 오늘 작성 억제");
  await pool.query("DELETE FROM notification_jobs WHERE kind='madi-reminder'; DELETE FROM journal_entries WHERE id='written-today'; INSERT INTO notification_presence VALUES('owner','tab',null,true,now()+interval '1 minute')");
  await dispatchNotifications(true, now, send); assert.equal(sent.length, 2, "작성 중 기록 알림 억제");
  await pool.query("DELETE FROM notification_presence; DELETE FROM notification_jobs");
  await saveNotificationSettings("owner", settings);
  await queue(); await pool.query("UPDATE notification_jobs SET due_at=now()-interval '1 second'; INSERT INTO notification_presence VALUES('owner','reader','book',false,now()+interval '1 minute')");
  await dispatchNotifications(true, new Date(), send); assert.equal(sent.length, 2, "열어 보고 있는 하루마디 소식 억제");
  await pool.query("DELETE FROM notification_presence; INSERT INTO harumadi_comments VALUES('parent','book','owner',null,null),('reply','book','member','parent',null)");
  await client.$transaction(tx => enqueueTogetherNotification(tx, "member", "book", "comment-reply", "reply", "owner"));
  await dispatchNotifications(true, new Date(), send); assert.equal(sent.at(-1)?.type, "comment-reply");
  await client.$transaction(tx => enqueueTogetherNotification(tx, "member", "book", "comment-reply", "reply", "owner"));
  await pool.query("UPDATE harumadi_comments SET deleted_at=now() WHERE id='reply'");
  await dispatchNotifications(true, new Date(), send); assert.equal(sent.length, 3, "삭제된 답글 알림 억제");
  await client.$transaction(tx => enqueueTogetherNotification(tx, "member", "book", "invite-accepted", "invite", "owner"));
  await dispatchNotifications(true, new Date(), send); assert.equal(sent.at(-1)?.type, "invite-accepted");
  await queue(); await pool.query("UPDATE notification_jobs SET due_at=now()-interval '1 second'");
  const failing = async () => ({ attempted: 1, sent: 0, failed: 1, invalidated: 0 });
  const failure = await dispatchNotifications(true, new Date(), failing);
  assert.equal("failed" in failure && failure.failed, 1);
  await dispatchNotifications(true, new Date(), send); assert.equal(sent.length, 4, "모호한 제공자 실패는 중복 재시도하지 않음");
  await pool.query("DELETE FROM notification_jobs");
  const { enqueueInquiryAnsweredNotification } = await import("../../src/server/notifications/outbox");
  const answerAt = new Date();
  await pool.query("INSERT INTO customer_inquiries VALUES('inquiry','owner','synthetic answer',$1)", [answerAt.toISOString()]);
  await client.$transaction(tx => enqueueInquiryAnsweredNotification(tx, "owner", "inquiry", answerAt));
  await client.$transaction(tx => enqueueInquiryAnsweredNotification(tx, "owner", "inquiry", answerAt));
  await dispatchNotifications(true, new Date(Date.now() + 10), send);
  assert.equal(sent.at(-1)?.type, "inquiry-answered");
  const beforeStale = sent.length;
  const staleAt = new Date(answerAt.getTime() - 1000);
  await client.$transaction(tx => enqueueInquiryAnsweredNotification(tx, "owner", "inquiry", staleAt));
  await dispatchNotifications(true, new Date(Date.now() + 10), send);
  assert.equal(sent.length, beforeStale, "이전 답변 버전은 알리지 않는다");
  await pool.query("DELETE FROM users WHERE id='owner'");
  assert.equal((await pool.query("SELECT count(1)::int AS n FROM notification_jobs WHERE user_id='owner'")).rows[0].n, 0);
  console.log(JSON.stringify({ default19: true, independentPreferences: true, ownerAccess: true, grouped: true, optOutEnforced: true, membershipRechecked: true, blocksRechecked: true, reminderOnceDaily: true, writingSuppressed: true, deletionCascades: true }));
} finally {
  await client.$disconnect(); delete (globalThis as { prisma?: unknown }).prisma;
  await pool.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`); await pool.end();
}
